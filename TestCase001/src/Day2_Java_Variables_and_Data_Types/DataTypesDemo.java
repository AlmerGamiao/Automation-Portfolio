package Day2_Java_Variables_and_Data_Types;

public class DataTypesDemo {

	public static void main (String args[]) {
//	Numeric Data Types
		int a=100,b=200,c=300;
		
	
		System.out.println("The Value of A and B is: "+a+" "+b);
		System.out.println("The Value of A and C is: "+a+" "+c);
		System.out.println("The Value of B and C is: "+b+" "+c);
		
	byte by = 123;
	System.out.println(by);
	
	short sh = 321;
	System.out.println(sh);
	
	long l=2131231231231L;
	System.out.println(l);
	
//	decimal Number float, double
	
	float item_price = 15.5f;
	System.out.println(item_price);
	double fbl = 123234.234234;
	System.out.println(fbl);
	
	char grad='A';
	System.out.println(grad);
	
	String name = "Tester";
	System.out.println(name);
	
//	char letters= 'ABC';
//	char letters1= "ABC";
	String letters1= "ABC";
	System.out.println(letters1);
	
	
	boolean f=true;
	System.out.println(f);	
	
	}
	
	
}
